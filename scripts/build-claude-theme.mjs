// Generate the CatGo light/dark theme variables injected into the Claude Code viewer.
// The packaged editor uses CatGo's theme variables but never defines them, so its
// dark fallbacks (for example the pencil palette) appear on light pages.
// Usage: node scripts/build-claude-theme.mjs <CatGo checkout>/src/lib/theme/themes.js
import {writeFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {pathToFileURL} from 'node:url'

const source = process.argv[2]
if (!source) throw new Error('Pass the path to CatGo src/lib/theme/themes.js.')
await import(pathToFileURL(resolve(source)).href)
const {light, dark} = globalThis.CATGO_THEMES
const block = (theme, indent) => Object.entries(theme).filter(([, value]) => value != null)
  .map(([key, value]) => `${indent}--${key}: ${value};`).join('\n')
// The editor shell reads the MCP Apps host style variables; this page is the host.
const css = `/* Generated by scripts/build-claude-theme.mjs from CatGo src/lib/theme/themes.js. */
:root {
${block(light, '  ')}
  --color-background-primary: var(--page-bg);
  --color-text-primary: var(--text-color);
}
@media (prefers-color-scheme: dark) {
  :root {
${block(dark, '    ')}
  }
}
`
await writeFile(new URL('../plugins/catgo-editor/assets/claude-theme.css', import.meta.url), css)
console.log(`${Object.keys(light).length} variables`)
